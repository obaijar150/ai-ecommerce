"""
License registry for every model and dataset the AI engine can use.

A short, explicit registry is the cheapest way to make "verify the license
before use" an enforceable, testable rule rather than a comment. The test suite
asserts that no non-permissive component is enabled by default.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum


class ComponentKind(str, Enum):
    """How a component relates to the AI engine."""

    BASELINE = "baseline"
    TRAINED = "trained"
    PRETRAINED = "pretrained"
    OPTIONAL = "optional"
    DATASET = "dataset"


@dataclass(frozen=True)
class LicenseInfo:
    """License metadata for a model or dataset.

    Attributes:
        name: Human-readable component name.
        license: SPDX-style license identifier.
        source: Where the component comes from (URL or description).
        kind: Relationship to the engine (baseline/trained/pretrained/...).
        permissive: Whether the license is permissive enough for any use.
        notes: Any caveats a reviewer should know about.
    """

    name: str
    license: str
    source: str
    kind: ComponentKind
    permissive: bool = True
    notes: str = ""


