def all_components() -> dict[str, LicenseInfo]:
    """Return every registered model and dataset keyed by identifier."""
    return {**MODEL_LICENSES, **DATASET_LICENSES}


def non_permissive_components() -> list[LicenseInfo]:
    """Return components whose licenses are not permissive."""
    return [info for info in all_components().values() if not info.permissive]


def assert_no_non_permissive_defaults(enabled: list[str]) -> None:
    """Raise ``ValueError`` if any enabled component is non-permissive.

    Args:
        enabled: Component identifiers that are enabled in the running config.
    """
    registry = all_components()
    offenders = [
        key for key in enabled if key in registry and not registry[key].permissive
    ]
    if offenders:
        raise ValueError(
            "Non-permissive components must not be enabled by default: "
            f"{offenders}"
        )
